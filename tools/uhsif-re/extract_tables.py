#!/usr/bin/env python3
"""Generate uhsif_tables.c for fw/uhsif from your copy of libUHSIF.a (lib.o).

The tables are WCH data and stay out of the repository; this script is how the open driver
gets them at build time.

usage: python3 -I extract_tables.py lib.o > uhsif_tables.c
"""
import struct
import sys
from elftools.elf.elffile import ELFFile

MODES = [  # (C index, regs symbol, suffix of the Wavedata/Position/Transition symbols)
    ("DEF_UHSIF_SLAVE_FPGA_MODE", "UhsifRegValue", "Slave_FPGA", "Slave_FPGA"),
    ("DEF_UHSIF_SLAVE_SOC_MODE", "UhsifRegValue", "Slave_SOC", "Slave_SOC"),
    ("DEF_UHSIF_MASTER_MODE", "UhsifRegValue_MASTER", "MASTER", "Master"),
]


def symbols(path):
    f = ELFFile(open(path, "rb"))
    out = {}
    for s in f.get_section_by_name(".symtab").iter_symbols():
        if s.name.startswith("Uhsif") and s["st_shndx"] not in ("SHN_UNDEF", "SHN_ABS"):
            data = f.get_section(s["st_shndx"]).data()
            out[s.name] = data[s["st_value"]:s["st_value"] + s["st_size"]]
    return out


def c_array(ctype, name, values, per_line, fmt):
    rows = [", ".join(fmt.format(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"


def main():
    sym = symbols(sys.argv[1])
    out = ["/* Generated by tools/uhsif-re/extract_tables.py from libUHSIF.a. Do not commit. */",
           '#include "uhsif.h"', ""]
    for regs in ("UhsifRegValue", "UhsifRegValue_MASTER"):
        words = struct.unpack(f"<{len(sym[regs]) // 4}I", sym[regs])
        assert len(words) == 76, regs
        out.append(c_array("uint32_t", regs, words, 4, "0x{:08x}u"))
    entries = []
    for idx, regs, wave, trans in MODES:
        pos = list(sym[f"UhsifWavedataPosition_{wave}"])
        wd = struct.unpack(f"<{len(sym[f'UhsifWavedata_{wave}']) // 4}I", sym[f"UhsifWavedata_{wave}"])
        tr = struct.unpack(f"<{len(sym[f'UhsifTransition_{trans}']) // 2}H", sym[f"UhsifTransition_{trans}"])
        assert len(wd) % 6 == 0 and max(pos) < len(wd) // 6, wave
        out.append(c_array("uint8_t", f"pos_{wave}", pos, 16, "{:3d}"))
        out.append(c_array("uint32_t", f"wave_{wave}", wd, 6, "0x{:08x}u"))
        out.append(c_array("uint16_t", f"trans_{wave}", tr, 8, "0x{:04x}"))
        entries.append(f"    [{idx}] = {{ {regs}, pos_{wave}, {len(pos)}, wave_{wave}, trans_{wave}, {len(tr)} }},")
    out.append("const uhsif_mode_tables_t uhsif_tables[3] = {\n" + "\n".join(entries) + "\n};")
    print("\n".join(out))


if __name__ == "__main__":
    main()
